"""Flutter example code (tflite_flutter) and a Colab fallback notebook for exported models."""

import json
import re
from typing import Dict, List

TFLITE_FLUTTER = "^0.12.1"  # pub.dev latest as of 2026-10


def safe_name(name: str) -> str:
    s = re.sub(r"[^A-Za-z0-9_]+", "_", name).strip("_").lower()
    return s or "model"


def _prod(xs: List[int]) -> int:
    out = 1
    for x in xs:
        out *= x
    return out


def generate(name: str, input_shape: List[int], output_shape: List[int], lang: str = "ko", layout: str = "NHWC") -> Dict[str, str]:
    n = safe_name(name)
    asset = "assets/models/%s.tflite" % n
    ko = lang == "ko"
    layout_note = {
        "NCHW": ("입력 순서는 (배치, 채널, 높이, 너비)예요. PyTorch 모델이라 채널이 앞에 와요 (channels first).",
                 "Input order is (batch, channels, height, width): channels first, as in PyTorch."),
        "NHWC": ("입력 순서는 (배치, 높이, 너비, 채널)예요 (channels last).", "Input order is (batch, height, width, channels): channels last."),
    }.get(layout, ("입력 숫자는 행 우선 순서로 넣어요.", "Pass the numbers in row-major order."))
    note = layout_note[0] if ko else layout_note[1]
    count_msg = "입력 숫자 개수는 $expected개여야 해요 (지금 ${input.length}개)." if ko else "Expected $expected input numbers, got ${input.length}."
    dart = f"""// DeepFriend가 만든 코드예요 / Generated by DeepFriend
// {"모델" if ko else "Model"}: {n}
// {note}
import 'package:tflite_flutter/tflite_flutter.dart';

class DeepFriendModel {{
  static const String assetPath = '{asset}';
  static const List<int> inputShape = [{', '.join(map(str, input_shape))}];
  static const List<int> outputShape = [{', '.join(map(str, output_shape))}];

  final Interpreter _interpreter;
  DeepFriendModel._(this._interpreter);

  /// {"앱이 시작할 때 한 번 불러요." if ko else "Load once when the app starts."}
  static Future<DeepFriendModel> load() async {{
    final interpreter = await Interpreter.fromAsset('{asset}');
    return DeepFriendModel._(interpreter);
  }}

  /// {"input에는 숫자 %d개를 넣어요. 결과로 숫자 %d개가 나와요." % (_prod(input_shape), _prod(output_shape)) if ko else "Pass %d numbers; returns %d numbers." % (_prod(input_shape), _prod(output_shape))}
  List<double> predict(List<double> input) {{
    final expected = inputShape.reduce((a, b) => a * b);
    if (input.length != expected) {{
      throw ArgumentError('{count_msg}');
    }}
    final output = List.filled(outputShape.reduce((a, b) => a * b), 0.0).reshape(outputShape);
    _interpreter.run(input.reshape(inputShape), output);
    return output.flatten<double>();
  }}

  void close() => _interpreter.close();
}}
"""
    pubspec = f"""# {"pubspec.yaml에 아래 내용을 추가하세요" if ko else "Add this to your pubspec.yaml"}
dependencies:
  tflite_flutter: {TFLITE_FLUTTER}

flutter:
  assets:
    - {asset}
"""
    if ko:
        readme = f"""# {n} — Flutter 앱에서 쓰기

1. `{n}.tflite` 파일을 Flutter 프로젝트의 `{asset}` 위치에 복사하세요.
2. `pubspec_snippet.yaml`의 내용을 `pubspec.yaml`에 추가하고 `flutter pub get`을 실행하세요.
3. `lib/deepfriend_model.dart`를 프로젝트의 `lib/` 폴더에 복사하세요.
4. 이렇게 써요:

```dart
final model = await DeepFriendModel.load();
final result = model.predict(inputNumbers); // 숫자 {_prod(input_shape)}개
```

- 입력 모양: `{tuple(input_shape)}` · 출력 모양: `{tuple(output_shape)}`
- {note}
- 학습할 때 입력을 정규화했다면(예: 0~1로 나누기) 앱에서도 똑같이 해 줘야 결과가 맞아요.
"""
    else:
        readme = f"""# {n} — use it in a Flutter app

1. Copy `{n}.tflite` to `{asset}` in your Flutter project.
2. Add `pubspec_snippet.yaml` to your `pubspec.yaml` and run `flutter pub get`.
3. Copy `lib/deepfriend_model.dart` into your `lib/` folder.
4. Use it:

```dart
final model = await DeepFriendModel.load();
final result = model.predict(inputNumbers); // {_prod(input_shape)} numbers
```

- Input shape: `{tuple(input_shape)}` · output shape: `{tuple(output_shape)}`
- {note}
- If you normalized inputs during training (e.g. divided by 255), do the same in the app.
"""
    return {"lib/deepfriend_model.dart": dart, "pubspec_snippet.yaml": pubspec, "README.md": readme}


def notebook(class_name: str, model_file: str, weights_file: str, input_shape: List[int], lang: str = "ko") -> str:
    """A Colab notebook that converts the PyTorch model on Linux when this computer cannot."""
    ko = lang == "ko"
    shape = "(" + ", ".join(map(str, input_shape)) + ")"

    def md(text: str) -> dict:
        return {"cell_type": "markdown", "metadata": {}, "source": [text]}

    def code(text: str) -> dict:
        return {"cell_type": "code", "metadata": {}, "execution_count": None, "outputs": [], "source": [text]}

    cells = [
        md(("# DeepFriend: PyTorch → TFLite 변환 (Colab)\n이 컴퓨터에서는 변환 도구를 쓸 수 없어서 Colab에서 변환해요. 위에서부터 차례로 실행하세요."
            if ko else "# DeepFriend: PyTorch → TFLite (Colab)\nThe converter is not available on this computer, so convert here. Run the cells top to bottom.")),
        code("!pip install litert-torch torchvision ai-edge-litert -q"),
        md(("`%s`와 `%s`를 업로드하세요." if ko else "Upload `%s` and `%s`.") % (model_file, weights_file or "(weights)")),
        code("from google.colab import files\nuploaded = files.upload()"),
        code(
            "import torch, litert_torch, importlib.util\n"
            f"spec = importlib.util.spec_from_file_location('user_model', {model_file!r})\n"
            "mod = importlib.util.module_from_spec(spec); spec.loader.exec_module(mod)\n"
            f"model = mod.{class_name}()\n"
            + (f"model.load_state_dict(torch.load({weights_file!r}, map_location='cpu', weights_only=True))\n" if weights_file else "")
            + f"example = torch.randn{shape}\n"
            "edge = litert_torch.convert(model.eval(), (example,))\n"
            f"edge.export('{class_name.lower()}.tflite')\n"
            f"files.download('{class_name.lower()}.tflite')"
        ),
    ]
    return json.dumps({"cells": cells, "metadata": {"kernelspec": {"name": "python3", "display_name": "Python 3"}}, "nbformat": 4, "nbformat_minor": 5}, ensure_ascii=False, indent=1)
